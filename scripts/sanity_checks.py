"""Two robustness checks of the main study, written to ``results/sanity_checks.md``.

Usage
-----
    python scripts/sanity_checks.py      # requires results/sweep.csv; about 5 min

1. **Is the classical baseline handicapped by this code base?** The RBF model is
   re-implemented with scikit-learn only: PCA, standardisation and the SVM form one
   ``Pipeline`` that ``GridSearchCV`` tunes with the preprocessing *refitted inside
   every fold*. If the shared-preprocessing shortcut or the precomputed-kernel code
   path distorted the baseline, the two implementations would disagree.

2. **Is the C grid wide enough?** Several selected models sit on the upper edge of
   the C grid. For the selected kernel of every family and seed, C is re-tuned on a
   grid that extends two decades further, and the test accuracy is compared.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from joblib import Parallel, delayed
from sklearn.decomposition import PCA
from sklearn.model_selection import GridSearchCV, StratifiedKFold
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC

from qksvm.analysis import FAMILIES, mean_and_ci, select_by_cv
from qksvm.data import RawSplit, load_fashion_mnist, make_binary_task
from qksvm.experiments import Config, kernel_from_record, prepare
from qksvm.model_selection import evaluate_kernel

EXTENDED_C_GRID = tuple(float(c) for c in np.logspace(-2, 4, 7))


def check_config(config: Config, selected: pd.DataFrame, train: RawSplit, test: RawSplit) -> dict:
    """Run both checks for one configuration."""
    grids = config.grids

    # 1. Independent scikit-learn implementation of the RBF baseline.
    task = make_binary_task(train, test, config.classes, config.n_train, config.seed)
    pipeline = Pipeline(
        [
            ("pca", PCA(config.n_features, svd_solver="full")),
            ("scale", StandardScaler()),
            ("svm", SVC(kernel="rbf")),
        ]
    )
    search = GridSearchCV(
        pipeline,
        {"svm__gamma": list(grids.rbf_gamma), "svm__C": list(grids.C)},
        cv=StratifiedKFold(config.n_folds, shuffle=True, random_state=config.seed),
    ).fit(task.X_train, task.y_train)
    ours = selected[selected.family == "RBF"].iloc[0]
    record = {
        **config.tags(),
        "rbf_sklearn": search.score(task.X_test, task.y_test),
        "rbf_ours": ours.test_accuracy,
    }

    # 2. Re-tune C for each selected kernel on the extended grid.
    data = prepare(config, train, test)
    for row in selected.to_dict("records"):
        evaluation = evaluate_kernel(
            kernel_from_record(row),
            data.Z_train,
            data.y_train,
            data.Z_test,
            data.y_test,
            EXTENDED_C_GRID,
            config.n_folds,
            config.seed,
        )
        record[f"{row['family']}|original"] = row["test_accuracy"]
        record[f"{row['family']}|extended"] = evaluation.test_accuracy
        record[f"{row['family']}|C"] = evaluation.C
    return record


def main() -> None:
    """Run the checks for every configuration of the main study."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--results", type=Path, default=Path("results"))
    parser.add_argument("--data", type=Path, default=Path("data/raw"))
    parser.add_argument("--n-train", type=int, default=512)
    parser.add_argument("--jobs", type=int, default=-1)
    args = parser.parse_args()

    sweep = pd.read_csv(args.results / "sweep.csv")
    selected = select_by_cv(sweep[sweep.n_train == args.n_train])
    train, test = load_fashion_mnist(args.data)

    groups = selected.groupby(["n_features", "n_train", "seed"])
    records = Parallel(n_jobs=args.jobs)(
        delayed(check_config)(Config(*map(int, key)), group, train, test) for key, group in groups
    )
    table = pd.DataFrame(records)
    table.to_csv(args.results / "sanity_checks.csv", index=False, float_format="%.6g")

    def pp(values: pd.Series) -> str:
        mean, half_width = mean_and_ci(100 * values)
        return f"{mean:+.2f} ± {half_width:.2f}"

    lines = [
        "# Sanity checks",
        "",
        "Generated by `scripts/sanity_checks.py`. Differences are in percentage points of "
        f"test accuracy (mean ± 95% CI half-width over seeds), N = {args.n_train}.",
        "",
        "## 1. RBF baseline: scikit-learn pipeline with preprocessing inside each fold",
        "",
        "| n_features | scikit-learn (%) | this repository (%) | difference |",
        "|-----------:|-----------------:|--------------------:|:-----------|",
    ]
    for n_features, group in table.groupby("n_features"):
        lines.append(
            f"| {n_features} | {100 * group.rbf_sklearn.mean():.2f} | "
            f"{100 * group.rbf_ours.mean():.2f} | {pp(group.rbf_ours - group.rbf_sklearn)} |"
        )
    lines += [
        "",
        f"## 2. Re-tuning C on {EXTENDED_C_GRID[0]:g} .. {EXTENDED_C_GRID[-1]:g}",
        "",
        "Change in test accuracy of each family's selected kernel (extended grid minus "
        "original grid), and the fraction of seeds where a C above the original maximum "
        "is chosen.",
        "",
        "| family | n_features | change | fraction with C > 100 |",
        "|:-------|-----------:|:-------|----------------------:|",
    ]
    for family in FAMILIES:
        for n_features, group in table.groupby("n_features"):
            change = group[f"{family}|extended"] - group[f"{family}|original"]
            above = (group[f"{family}|C"] > 100).mean()
            lines.append(f"| {family} | {n_features} | {pp(change)} | {above:.2f} |")
    (args.results / "sanity_checks.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
